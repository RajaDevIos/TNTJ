// ---- daees (live page "மாவட்ட பேச்சாளர்கள்")
const daeeText = clean(page('மாவட்ட பேச்சாளர்கள்').replace(/<br\s*\/?>|<\/(p|div|tr)>/gi, '\n')).length
  ? page('மாவட்ட பேச்சாளர்கள்').replace(/<br\s*\/?>|<\/(p|div|tr|li)>/gi, '\n').replace(/<\/t[dh]>/gi, '\t').replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ')
  : '';
const daees = [];
for (const line of daeeText.split('\n')) {
  const m = line.match(/^\s*(\d+)\.?\s+(.+?)\s*[\t|]\s*(.*)$/) || line.match(/^\s*(\d+)\.?\s+(.+?)\s{2,}([\d\s\-.]+)$/);
  if (!m) continue;
  let name = m[2].replace(/\|/g, '').trim();
  let qual = null;
  const qm = name.match(/\s(MISC|M\.I\.Sc|tpl)\s*$/i);
  if (qm && /misc|m\.i\.sc/i.test(qm[1])) { qual = 'M.I.Sc'; name = name.slice(0, qm.index).trim(); }
  daees.push({ name, qualification: qual, phone: phone(m[3]), sort_order: daees.length + 1 });
}
sql += ins('daees', ['name', 'qualification', 'phone', 'sort_order'], daees);

// ---- branches + officers (live page "கிளை நிர்வாகிகள் தொடர்புக்கு")
const brHtml = page('கிளை நிர்வாகிகள்');
const accs = brHtml.split('<div class="acc"').slice(1);
const branches = [], officers = [];
accs.forEach((a, bi) => {
  const name = clean((a.match(/class="head"[^>]*>([\s\S]*?)<\/div>/) || [])[1] || '').replace('📂', '').trim();
  if (!name) return;
  const id = branches.length + 1;
  branches.push({ id, name, sort_order: id });
  for (const r of a.matchAll(/<tr><td>([\s\S]*?)<\/td><td>([\s\S]*?)<\/td><td>([\s\S]*?)<\/td><\/tr>/g)) {
    const role = clean(r[1]).replace('👤', '').trim();
    const nm = clean(r[2]);
    if (!nm || nm === '-') continue;
    officers.push({ branch_id: id, role, name: nm, phone: phone(clean(r[3])), sort_order: officers.filter(o => o.branch_id === id).length + 1 });
  }
});
sql += ins('branches', ['id', 'name', 'sort_order'], branches);
sql += ins('branch_officers', ['branch_id', 'role', 'name', 'phone', 'sort_order'], officers);

