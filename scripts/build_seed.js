// ---- news + monthly reports (latest posts)
const posts = fs.readdirSync(dir).filter(f => /^posts_\d+\.json$/.test(f))
  .flatMap(f => JSON.parse(fs.readFileSync(path.join(dir, f))).feed.entry || []);
const branchByLabel = l => {
  const n = l.replace(/[.\s]+$/g, '').replace(/\s*கிளை.*$/, '').trim();
  const b = branches.find(b => b.name.replace(/\s/g, '') === n.replace(/\s/g, '') || n.startsWith(b.name) || b.name.startsWith(n));
  return b ? b.id : null;
};
const tamilMonths = { 'ஜனவரி': 1, 'பிப்ரவரி': 2, 'மார்ச்': 3, 'ஏப்ரல்': 4, 'மே': 5, 'ஜுன்': 6, 'ஜூன்': 6, 'ஜூலை': 7, 'ஆகஸ்ட்': 8, 'செப்டம்பர்': 9, 'அக்டோபர்': 10, 'நவம்பர்': 11, 'டிசம்பர்': 12 };
const news = [], reports = [];
const seenSlug = new Set();
for (const p of posts) {
  const title = clean(p.title.$t);
  const body = (p.content && p.content.$t) || '';
  const img = (body.match(/<img[^>]+src="([^"]+)"/) || [])[1] || null;
  const labels = (p.category || []).map(c => c.term);
  const sid = p.id.$t.split('post-').pop();
  const pub = p.published.$t.slice(0, 19).replace('T', ' ');
  const mm = title.match(/^(\S+)\s+(\d{4})\s+மாதாந்திர/);
  if (mm && tamilMonths[mm[1]]) {
    const d = `${mm[2]}-${String(tamilMonths[mm[1]]).padStart(2, '0')}-01`;
    if (!reports.find(r => r.report_month === d)) reports.push({ report_month: d, title, image: img ? img.replace(/\/s\d+(-[a-z]+)?\//, '/s1600/') : null });
  }
  const cat = labels.find(l => !branchByLabel(l)) || (labels.length ? 'கிளை செய்திகள்' : 'செய்திகள்');
  const branchId = labels.map(branchByLabel).find(Boolean) || null;
  let slug = 'post-' + sid; if (seenSlug.has(slug)) continue; seenSlug.add(slug);
  news.push({ title, slug, category: cat === 'Monthly points' ? 'மாதாந்திர புள்ளிப்பட்டியல்' : cat, branch_id: branchId, image: img, body, source_id: sid, published_at: pub });
}
sql += ins('monthly_reports', ['report_month', 'title', 'image'], reports);
for (let i = 0; i < news.length; i += 50) sql += ins('news', ['title', 'slug', 'category', 'branch_id', 'image', 'body', 'source_id', 'published_at'], news.slice(i, i + 50));

